package Array;

import java.util.Scanner;

public class other_datatype  {
    public static void main(String[] args) {
        Scanner sc=new Scanner(System.in);
        int n=sc.nextInt();
        char[] arr=new char[n];
        for(int i=0;i<n;i++){
            System.out.print(arr[i]+" ");
        }
    }
}
